//! `legion audit` journals every run it writes to `--out`, `legion verify`
//! checks that journal, `--resume` continues an interrupted run from signed
//! receipts, and `--max-parallel` never changes what a run records.

use legion_audit::journal::{AuditEvent, EventKind, Journal, ANCHOR_FILE, EVENTS_FILE, HEAD_FILE};
use serde_json::Value;
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
    sync::atomic::{AtomicU64, Ordering},
};

struct Fixture {
    repo: PathBuf,
    out: PathBuf,
    home: PathBuf,
    state: PathBuf,
}

impl Fixture {
    fn new() -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let base = fs::canonicalize(std::env::temp_dir())
            .unwrap()
            .join(format!(
                "legion-audit-journal-cli-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
        let _ = fs::remove_dir_all(&base);
        let fixture = Self {
            repo: base.join("repo"),
            out: base.join("run"),
            home: base.join("home"),
            state: base.join("state"),
        };
        fs::create_dir_all(fixture.repo.join("src")).unwrap();
        fs::create_dir_all(&fixture.home).unwrap();
        fs::create_dir_all(&fixture.state).unwrap();
        fixture.write(
            "Cargo.toml",
            "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        );
        fixture.write(
            "src/lib.rs",
            "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n",
        );
        fixture.write("README.md", "# Fixture\n");
        fixture.write(
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n",
        );
        for args in [
            &["init", "-q"][..],
            &["config", "user.email", "e2e@example.invalid"],
            &["config", "user.name", "e2e"],
            &["config", "commit.gpgsign", "false"],
            &["add", "-A"],
            &["commit", "-q", "-m", "fixture"],
        ] {
            let output = fixture.git(args);
            assert!(output.status.success(), "git {args:?} failed");
        }
        fixture
    }

    fn base(&self) -> PathBuf {
        self.repo.parent().unwrap().to_path_buf()
    }

    fn write(&self, relative: &str, text: &str) {
        let path = self.repo.join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }

    fn git(&self, args: &[&str]) -> Output {
        Command::new("git")
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.base())
            .args(args)
            .output()
            .unwrap()
    }

    fn legion(&self, args: &[&str]) -> Output {
        let registry =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/registry/providers.json");
        Command::new(env!("CARGO_BIN_EXE_legion"))
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.base())
            .env("HOME", &self.home)
            .env("USERPROFILE", &self.home)
            .env("LOCALAPPDATA", self.home.join("AppData/Local"))
            .env("XDG_DATA_HOME", self.home.join(".local/share"))
            .env("LEGION_STATE_ROOT", &self.state)
            .env("LEGION_PROVIDER_REGISTRY", registry)
            .env_remove("AUDIT_PLAN_SIGNING_KEY")
            .env_remove("LEGION_NATIVE_APPLICATION_CONFIG")
            .args(args)
            .output()
            .unwrap()
    }

    /// Run `legion audit` into `out` with extra flags; the run may be clean
    /// (0) or incomplete (2) depending on the host's tools.
    fn audit_into(&self, out: &Path, extra: &[&str]) -> Value {
        let mut args = vec![
            "audit",
            self.repo.to_str().unwrap(),
            "--out",
            out.to_str().unwrap(),
            "--json",
        ];
        args.extend_from_slice(extra);
        let output = self.legion(&args);
        assert!(
            matches!(output.status.code(), Some(0) | Some(2)),
            "audit failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        json_of("audit", &output)
    }

    fn verify(&self, run: &Path) -> Value {
        json_of(
            "verify",
            &self.legion(&["verify", run.to_str().unwrap(), "--json"]),
        )
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(self.base());
    }
}

fn json_of(label: &str, output: &Output) -> Value {
    serde_json::from_slice(&output.stdout).unwrap_or_else(|error| {
        panic!(
            "{label} stdout is not JSON ({error}): stdout={} stderr={}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        )
    })
}

fn events_of(run: &Path) -> Vec<AuditEvent> {
    fs::read_to_string(run.join(EVENTS_FILE))
        .unwrap()
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
        .collect()
}

fn errors_of(verified: &Value) -> Vec<String> {
    verified["contentErrors"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|e| e.as_str().map(str::to_owned))
        .collect()
}

fn has_journal_defect(verified: &Value, code: &str) -> bool {
    errors_of(verified)
        .iter()
        .any(|e| e.starts_with(&format!("journal-defect:{code}")))
}

#[test]
fn cli_run_creates_finalizes_and_verifies_its_journal() {
    let fixture = Fixture::new();
    let summary = fixture.audit_into(&fixture.out, &[]);

    for name in [
        EVENTS_FILE,
        HEAD_FILE,
        ANCHOR_FILE,
        "run-metrics.json",
        "journal-binding.json",
        "provider-receipts",
    ] {
        assert!(fixture.out.join(name).exists(), "{name} missing");
    }
    let events = events_of(&fixture.out);
    assert_eq!(events.first().unwrap().kind, EventKind::PlanFrozen);
    assert_eq!(events.last().unwrap().kind, EventKind::ReportFinalized);
    assert!(events
        .iter()
        .any(|event| event.kind == EventKind::ProviderStarted));
    assert!(events.iter().any(|event| matches!(
        event.kind,
        EventKind::ProviderFinished | EventKind::ProviderSkipped | EventKind::ProviderFailed
    )));

    // stdout, report and metrics all record the same head.
    assert_eq!(summary["journal"]["finalized"], Value::Bool(true));
    assert_eq!(summary["journal"]["eventCount"], events.len());
    let report: Value =
        serde_json::from_slice(&fs::read(fixture.out.join("report.json")).unwrap()).unwrap();
    let sealed = &report["claims"]["journalSealedAt"];
    assert_eq!(sealed["eventCount"], events.len() - 1);
    assert_eq!(
        sealed["digest"],
        Value::String(events[events.len() - 2].digest.clone())
    );
    let metrics: Value =
        serde_json::from_slice(&fs::read(fixture.out.join("run-metrics.json")).unwrap()).unwrap();
    assert_eq!(metrics["authoritative"], Value::Bool(false));

    let verified = fixture.verify(&fixture.out);
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_eq!(verified["journal"]["status"], "verified", "{verified:#}");
    assert!(verified["warnings"].as_array().unwrap().is_empty());
}

#[test]
fn tampered_truncated_or_removed_journal_fails_verification_with_a_named_reason() {
    let fixture = Fixture::new();
    fixture.audit_into(&fixture.out, &[]);
    let events_path = fixture.out.join(EVENTS_FILE);
    let original = fs::read_to_string(&events_path).unwrap();

    // Edited event content.
    let edited = original.replacen("provider_started", "provider_skipped", 1);
    assert_ne!(edited, original);
    fs::write(&events_path, &edited).unwrap();
    let verified = fixture.verify(&fixture.out);
    assert_ne!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_ne!(verified["complete"], Value::Bool(true));
    assert!(
        errors_of(&verified)
            .iter()
            .any(|e| e.starts_with("journal-defect:")),
        "{verified:#}"
    );

    // Tail cut off (finalization removed): the seal and the anchor both object.
    let mut lines: Vec<&str> = original.lines().collect();
    lines.pop();
    fs::write(&events_path, lines.join("\n") + "\n").unwrap();
    let verified = fixture.verify(&fixture.out);
    assert_ne!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert!(
        has_journal_defect(&verified, "truncated")
            || has_journal_defect(&verified, "not_finalized"),
        "{verified:#}"
    );
    fs::write(&events_path, &original).unwrap();

    // A run that shows evidence of a journal cannot shed it: removing every
    // journal file is a failure, not the legacy `journal-absent` warning.
    for name in [EVENTS_FILE, HEAD_FILE, ANCHOR_FILE] {
        fs::rename(
            fixture.out.join(name),
            fixture.out.join(format!("{name}.bak")),
        )
        .unwrap();
    }
    let verified = fixture.verify(&fixture.out);
    assert_ne!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert!(has_journal_defect(&verified, "unreadable"), "{verified:#}");

    // Restored, it verifies again.
    for name in [EVENTS_FILE, HEAD_FILE, ANCHOR_FILE] {
        fs::rename(
            fixture.out.join(format!("{name}.bak")),
            fixture.out.join(name),
        )
        .unwrap();
    }
    let verified = fixture.verify(&fixture.out);
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
}

#[test]
fn legacy_run_without_a_journal_warns_and_still_verifies() {
    let fixture = Fixture::new();
    fixture.audit_into(&fixture.out, &[]);
    // Rewrite the run as a pre-journal run: no journal files, no markers.
    for name in [
        EVENTS_FILE,
        HEAD_FILE,
        ANCHOR_FILE,
        "run-metrics.json",
        "journal-binding.json",
    ] {
        let _ = fs::remove_file(fixture.out.join(name));
    }
    let _ = fs::remove_dir_all(fixture.out.join("provider-receipts"));
    let plan_path = fixture.out.join("plan.json");
    let mut plan: Value = serde_json::from_slice(&fs::read(&plan_path).unwrap()).unwrap();
    plan.as_object_mut().unwrap().remove("journal");
    fs::write(&plan_path, serde_json::to_vec(&plan).unwrap()).unwrap();
    let report_path = fixture.out.join("report.json");
    let mut report: Value = serde_json::from_slice(&fs::read(&report_path).unwrap()).unwrap();
    report["claims"]
        .as_object_mut()
        .unwrap()
        .remove("journalSealedAt");
    fs::write(&report_path, serde_json::to_vec(&report).unwrap()).unwrap();

    let verified = fixture.verify(&fixture.out);
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_eq!(verified["journal"]["status"], "absent");
    assert!(verified["warnings"]
        .as_array()
        .unwrap()
        .iter()
        .any(|w| w.as_str().unwrap_or("").starts_with("journal-absent")));
}

#[test]
fn resume_refuses_misuse_and_a_finalized_run() {
    let fixture = Fixture::new();
    fixture.audit_into(&fixture.out, &[]);
    let repo = fixture.repo.to_str().unwrap();
    let run = fixture.out.to_str().unwrap();

    let finalized = fixture.legion(&["audit", repo, "--resume", run, "--json"]);
    assert_eq!(finalized.status.code(), Some(5), "{finalized:?}");
    assert!(String::from_utf8_lossy(&finalized.stderr).contains("resume refused"));

    let other = fixture.base().join("other-run");
    let mismatched = fixture.legion(&[
        "audit",
        repo,
        "--resume",
        run,
        "--out",
        other.to_str().unwrap(),
    ]);
    assert_eq!(mismatched.status.code(), Some(4));
    let plan_only = fixture.legion(&["audit", repo, "--resume", run, "--plan-only"]);
    assert_eq!(plan_only.status.code(), Some(4));
    let missing = fixture.base().join("never-run");
    let absent = fixture.legion(&["audit", repo, "--resume", missing.to_str().unwrap()]);
    assert_ne!(absent.status.code(), Some(0));

    // A fresh run may reuse a finished run's directory (journal cleared), but
    // an unfinished journal is never silently replaced.
    fixture.audit_into(&fixture.out, &[]);
    let mut lines: Vec<String> = fs::read_to_string(fixture.out.join(EVENTS_FILE))
        .unwrap()
        .lines()
        .map(str::to_owned)
        .collect();
    lines.pop();
    fs::write(fixture.out.join(EVENTS_FILE), lines.join("\n") + "\n").unwrap();
    let refused = fixture.legion(&["audit", repo, "--out", run, "--json"]);
    assert_eq!(refused.status.code(), Some(4), "{refused:?}");
    assert!(String::from_utf8_lossy(&refused.stderr).contains("--resume"));
}

#[test]
fn resume_reuses_verified_providers_and_reruns_only_the_interrupted_one() {
    let fixture = Fixture::new();
    fixture.audit_into(&fixture.out, &[]);
    let original = events_of(&fixture.out);
    let plan_digest = original[0].plan_digest.clone();

    // Rebuild the journal a crash would have left: everything before the last
    // provider finish, with that provider started and never finished.
    let cut = original
        .iter()
        .rposition(|event| event.kind == EventKind::ProviderFinished)
        .expect("at least one provider finished");
    let interrupted = original[cut].subject.clone();
    let finished_before: Vec<String> = original[..cut]
        .iter()
        .filter(|event| event.kind == EventKind::ProviderFinished)
        .map(|event| event.subject.clone())
        .collect();
    for name in [EVENTS_FILE, HEAD_FILE, ANCHOR_FILE, "run-metrics.json"] {
        fs::remove_file(fixture.out.join(name)).unwrap();
    }
    {
        let mut journal = Journal::create(&fixture.out, &plan_digest, 1_000).unwrap();
        for event in &original[1..cut] {
            journal
                .append(event.kind, &event.subject, &event.payload_digest, event.at)
                .unwrap();
        }
    }

    let output = fixture.legion(&[
        "audit",
        fixture.repo.to_str().unwrap(),
        "--resume",
        fixture.out.to_str().unwrap(),
        "--json",
    ]);
    assert!(
        matches!(output.status.code(), Some(0) | Some(2)),
        "resume failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let summary = json_of("resume", &output);
    assert_eq!(summary["journal"]["resumed"], Value::Bool(true));
    let mut reused: Vec<String> = summary["journal"]["reusedProviders"]
        .as_array()
        .unwrap()
        .iter()
        .map(|p| p.as_str().unwrap().to_owned())
        .collect();
    reused.sort();
    let mut expected = finished_before;
    expected.sort();
    assert_eq!(reused, expected, "only receipted completions are reused");
    assert!(!reused.contains(&interrupted));

    let resumed = events_of(&fixture.out);
    assert_eq!(resumed.last().unwrap().kind, EventKind::ReportFinalized);
    assert_eq!(
        resumed
            .iter()
            .filter(|event| event.kind == EventKind::RunResumed)
            .count(),
        1
    );
    // Reused providers are never started again.
    for provider in &expected {
        let starts = resumed
            .iter()
            .filter(|e| e.kind == EventKind::ProviderStarted && &e.subject == provider)
            .count();
        assert_eq!(starts, 1, "{provider} must not be re-executed");
    }
    // The interrupted provider is rerun (idempotent) or an explicit gap.
    let gaps: Vec<&str> = summary["journal"]["gapProviders"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(Value::as_str)
        .collect();
    let restarts = resumed
        .iter()
        .filter(|e| e.kind == EventKind::ProviderStarted && e.subject == interrupted)
        .count();
    assert!(
        (gaps.contains(&interrupted.as_str()) && restarts == 1)
            || (!gaps.contains(&interrupted.as_str()) && restarts == 2),
        "gaps={gaps:?} restarts={restarts}"
    );

    let verified = fixture.verify(&fixture.out);
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_eq!(verified["journal"]["status"], "verified", "{verified:#}");
}

#[test]
fn max_parallel_run_is_equivalent_to_the_sequential_run() {
    let fixture = Fixture::new();
    let sequential = fixture.base().join("run-sequential");
    let parallel = fixture.base().join("run-parallel");
    let one = fixture.audit_into(&sequential, &["--max-parallel", "1"]);
    let four = fixture.audit_into(&parallel, &["--max-parallel", "4"]);
    for key in [
        "planDigest",
        "auditStatus",
        "resultCount",
        "gaps",
        "plannedProviders",
    ] {
        assert_eq!(one[key], four[key], "{key}");
    }
    // Same providers, same results, recorded in frozen plan order.
    let execution = |run: &Path| -> Value {
        serde_json::from_slice(&fs::read(run.join("execution.json")).unwrap()).unwrap()
    };
    assert_eq!(
        execution(&sequential)["plannedProviders"],
        execution(&parallel)["plannedProviders"]
    );
    let results = |run: &Path| -> Vec<String> {
        execution(run)["results"]
            .as_array()
            .unwrap()
            .iter()
            .map(|r| r["provider"].as_str().unwrap().to_owned())
            .collect()
    };
    assert_eq!(results(&sequential), results(&parallel));
    // The journals differ only in order and time; both verify, and the
    // replay-equivalence digest (volatile fields removed) is identical.
    let verified = json_of(
        "verify",
        &fixture.legion(&[
            "verify",
            parallel.to_str().unwrap(),
            "--replay",
            sequential.to_str().unwrap(),
            "--json",
        ]),
    );
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_eq!(verified["replay"]["status"], "equivalent", "{verified:#}");

    // Out-of-range values are refused by the argument parser.
    let zero = fixture.legion(&[
        "audit",
        fixture.repo.to_str().unwrap(),
        "--max-parallel",
        "0",
    ]);
    assert_ne!(zero.status.code(), Some(0));
}
