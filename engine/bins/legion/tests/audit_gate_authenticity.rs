//! The audit gate must not trust editable run artifacts: a forged
//! `report.json`, an unsigned plan, a filtered selection or a typo'd profile
//! can never produce a better verdict than the verified evidence supports.

use legion_audit::assurance::{summarize, AuditAssuranceV1, ObligationStatus};
use serde_json::{json, Value};
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
    sync::atomic::{AtomicU64, Ordering},
};

struct Fixture {
    repo: PathBuf,
    out: PathBuf,
    home: PathBuf,
    state: PathBuf,
}

impl Fixture {
    /// A Rust-only repository: every Android provider is inapplicable.
    fn new() -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let base = fs::canonicalize(std::env::temp_dir())
            .unwrap()
            .join(format!(
                "legion-gate-authenticity-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
        let _ = fs::remove_dir_all(&base);
        let fixture = Self {
            repo: base.join("repo"),
            out: base.join("run"),
            home: base.join("home"),
            state: base.join("state"),
        };
        fs::create_dir_all(fixture.repo.join("src")).unwrap();
        fs::create_dir_all(&fixture.home).unwrap();
        fs::create_dir_all(&fixture.state).unwrap();
        for (path, text) in [
            (
                "Cargo.toml",
                "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
            ),
            (
                "src/lib.rs",
                "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n",
            ),
            ("README.md", "# Fixture\n"),
            (
                "Cargo.lock",
                "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n",
            ),
        ] {
            fs::write(fixture.repo.join(path), text).unwrap();
        }
        for args in [
            &["init", "-q"][..],
            &["config", "user.email", "e2e@example.invalid"],
            &["config", "user.name", "e2e"],
            &["config", "commit.gpgsign", "false"],
            &["add", "-A"],
            &["commit", "-q", "-m", "fixture"],
        ] {
            let output = Command::new("git")
                .current_dir(&fixture.repo)
                .env("GIT_CEILING_DIRECTORIES", &base)
                .args(args)
                .output()
                .unwrap();
            assert!(output.status.success(), "git {args:?} failed");
        }
        fixture
    }

    fn legion(&self, args: &[&str]) -> Output {
        let registry =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/registry/providers.json");
        Command::new(env!("CARGO_BIN_EXE_legion"))
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.repo.parent().unwrap())
            .env("HOME", &self.home)
            .env("USERPROFILE", &self.home)
            .env("LOCALAPPDATA", self.home.join("AppData/Local"))
            .env("XDG_DATA_HOME", self.home.join(".local/share"))
            .env("LEGION_STATE_ROOT", &self.state)
            .env("LEGION_PROVIDER_REGISTRY", registry)
            .env_remove("AUDIT_PLAN_SIGNING_KEY")
            .env_remove("LEGION_NATIVE_APPLICATION_CONFIG")
            .args(args)
            .output()
            .unwrap()
    }

    fn audit(&self, extra: &[&str]) -> Output {
        let mut args = vec![
            "audit",
            self.repo.to_str().unwrap(),
            "--out",
            self.out.to_str().unwrap(),
            "--json",
        ];
        args.extend_from_slice(extra);
        self.legion(&args)
    }

    fn audit_ok(&self, extra: &[&str]) {
        let output = self.audit(extra);
        assert!(
            matches!(output.status.code(), Some(0) | Some(2)),
            "audit failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    fn gate_output(&self, env: Option<(&str, &str)>, extra: &[&str]) -> Output {
        let registry =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/registry/providers.json");
        let mut command = Command::new(env!("CARGO_BIN_EXE_legion"));
        command
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.repo.parent().unwrap())
            .env("HOME", &self.home)
            .env("USERPROFILE", &self.home)
            .env("LOCALAPPDATA", self.home.join("AppData/Local"))
            .env("XDG_DATA_HOME", self.home.join(".local/share"))
            .env("LEGION_STATE_ROOT", &self.state)
            .env("LEGION_PROVIDER_REGISTRY", registry)
            .env_remove("AUDIT_PLAN_SIGNING_KEY")
            .env_remove("LEGION_NATIVE_APPLICATION_CONFIG")
            .args(["audit", "gate", "--run", self.out.to_str().unwrap()])
            .args(extra);
        if let Some((name, value)) = env {
            command.env(name, value);
        }
        command.output().unwrap()
    }

    fn gate(&self, extra: &[&str]) -> (Option<i32>, Value) {
        let mut args = vec!["audit", "gate", "--run", self.out.to_str().unwrap()];
        args.extend_from_slice(extra);
        let output = self.legion(&args);
        let value = serde_json::from_slice(&output.stdout).unwrap_or(Value::Null);
        (output.status.code(), value)
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(self.repo.parent().unwrap());
    }
}

fn read_json(path: &Path) -> Value {
    serde_json::from_slice(&fs::read(path).unwrap()).unwrap()
}

fn reasons(value: &Value) -> Vec<String> {
    value["reasons"]
        .as_array()
        .map(|items| {
            items
                .iter()
                .filter_map(|item| item.as_str().map(str::to_owned))
                .collect()
        })
        .unwrap_or_default()
}

#[test]
fn forged_report_with_fabricated_satisfied_obligations_is_not_eligible() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "release"]);
    let report_path = fixture.out.join("report.json");
    let mut report = read_json(&report_path);
    // ReportV2 (the default `report.json`) flattens extensions to the top level.
    let key = "/auditAssuranceV1";
    let extension = report
        .pointer(key)
        .cloned()
        .expect("release run carries an assurance extension");
    let mut assurance = AuditAssuranceV1::from_value(&extension, "2026-10-23T00:00:00Z").unwrap();
    for obligation in &mut assurance.obligations {
        if obligation.status != ObligationStatus::Inapplicable {
            obligation.status = ObligationStatus::Satisfied;
            obligation.reason = None;
            obligation.evidence_refs = vec!["fabricated-evidence".into()];
            obligation.denominator = None;
        }
    }
    assurance.summary = summarize(assurance.profile.profile, &assurance.obligations);
    *report.pointer_mut(key).unwrap() = assurance.to_value().unwrap();
    report["status"] = json!("clean");
    report["gaps"] = json!([]);
    report["findings"] = json!([]);
    fs::write(&report_path, serde_json::to_vec(&report).unwrap()).unwrap();

    let (code, verdict) = fixture.gate(&["--profile", "release"]);
    assert_ne!(
        code,
        Some(0),
        "forged report must never be eligible: {verdict}"
    );
    assert_ne!(verdict["verdict"], json!("eligible"));
    assert!(
        reasons(&verdict)
            .iter()
            .any(|r| r.starts_with("claim-mismatch:")
                || r.starts_with("report-differs-from-finalized-digest")),
        "the disagreement must be named: {verdict}"
    );
}

#[test]
fn unsigned_plan_is_refused() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr"]);
    let plan_path = fixture.out.join("plan.json");
    let mut plan = read_json(&plan_path);
    plan["nativePlan"]["signature"] = Value::Null;
    fs::write(&plan_path, serde_json::to_vec(&plan).unwrap()).unwrap();
    let (code, _) = fixture.gate(&["--profile", "pre-pr"]);
    assert_eq!(
        code,
        Some(5),
        "an unsigned assurance plan is an integrity failure"
    );
}

#[test]
fn filtered_pre_pr_run_on_a_rust_only_repository_is_incomplete() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr", "--only", "code.android.lint"]);
    let (code, verdict) = fixture.gate(&["--profile", "pre-pr"]);
    assert_eq!(code, Some(2), "{verdict}");
    assert_eq!(verdict["fullScope"], json!(false));
    assert!(reasons(&verdict)
        .iter()
        .any(|r| r.starts_with("filtered-run:only=code.android.lint")));
}

#[test]
fn skip_filter_is_incomplete_for_every_profile() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "repository", "--skip", "code.android.lint"]);
    let (code, verdict) = fixture.gate(&["--profile", "repository"]);
    assert_eq!(code, Some(2), "{verdict}");
    assert!(reasons(&verdict)
        .iter()
        .any(|r| r.starts_with("filtered-run:")));
}

#[test]
fn unknown_or_mistyped_profile_is_a_usage_error() {
    let fixture = Fixture::new();
    for bad in ["releaes", "Release", "pre_pr"] {
        let output = fixture.audit(&["--profile", bad]);
        assert_eq!(output.status.code(), Some(4), "profile {bad}");
    }
}

#[test]
fn bare_gate_requires_release_strength_and_says_so() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr"]);
    let (code, verdict) = fixture.gate(&[]);
    assert_ne!(code, Some(0));
    assert_eq!(verdict["requiredProfile"], json!("release"));
    assert_eq!(verdict["requiredProfileSource"], json!("default-release"));
    assert_eq!(verdict["frozenProfile"], json!("pre-pr"));
    let (_, explicit) = fixture.gate(&["--profile", "pre-pr"]);
    assert_eq!(explicit["requiredProfile"], json!("pre-pr"));
    assert_eq!(explicit["requiredProfileSource"], json!("explicit"));
}

#[test]
fn planted_run_dir_key_with_stripped_host_binding_is_refused() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr"]);
    fs::write(
        fixture.out.join("epoch.key"),
        "attacker-chosen-signing-key\n",
    )
    .unwrap();
    let plan_path = fixture.out.join("plan.json");
    let mut plan = read_json(&plan_path);
    plan.as_object_mut().unwrap().remove("planKey");
    plan.as_object_mut().unwrap().remove("epoch");
    fs::write(&plan_path, serde_json::to_vec(&plan).unwrap()).unwrap();
    let output = fixture.gate_output(None, &["--profile", "pre-pr"]);
    assert_eq!(output.status.code(), Some(5));
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(text.contains("plan-key-custody"), "{text}");
}

#[test]
fn environment_supplied_plan_key_is_refused_at_the_gate() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr"]);
    let output = fixture.gate_output(
        Some(("AUDIT_PLAN_SIGNING_KEY", "attacker-chosen-signing-key")),
        &["--profile", "pre-pr"],
    );
    assert_eq!(output.status.code(), Some(5));
    let text = format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(text.contains("plan-key-custody:environment"), "{text}");
}

#[test]
fn genuine_host_custody_run_reports_custody_registry_digest_and_imports() {
    let fixture = Fixture::new();
    fixture.audit_ok(&["--profile", "pre-pr"]);
    let (code, verdict) = fixture.gate(&["--profile", "pre-pr"]);
    assert_ne!(code, Some(5), "{verdict}");
    assert_eq!(verdict["keyCustody"], json!("host-state"));
    assert!(verdict["registryDigest"]
        .as_str()
        .is_some_and(|digest| digest.starts_with("sha256:")));
    assert_eq!(verdict["importsCounted"], json!(false));
}
