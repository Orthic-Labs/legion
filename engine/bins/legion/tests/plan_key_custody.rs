//! Plan-signing key custody: the per-run HMAC key lives in host state, never
//! in the run directory; a run whose key is gone is `unverifiable-signature`.

use serde_json::Value;
use std::{
    fs,
    path::{Path, PathBuf},
    process::{Command, Output},
    sync::atomic::{AtomicU64, Ordering},
};

struct Fixture {
    repo: PathBuf,
    out: PathBuf,
    home: PathBuf,
    state: PathBuf,
}

impl Fixture {
    fn new() -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let base = fs::canonicalize(std::env::temp_dir())
            .unwrap()
            .join(format!(
                "legion-plan-key-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
        let _ = fs::remove_dir_all(&base);
        let fixture = Self {
            repo: base.join("repo"),
            out: base.join("run"),
            home: base.join("home"),
            state: base.join("state"),
        };
        fs::create_dir_all(fixture.repo.join("src")).unwrap();
        fs::create_dir_all(&fixture.home).unwrap();
        fs::create_dir_all(&fixture.state).unwrap();
        fixture.write(
            "Cargo.toml",
            "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        );
        fixture.write(
            "src/lib.rs",
            "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n",
        );
        fixture.write("README.md", "# Fixture\n");
        fixture.write(
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\n",
        );
        for args in [
            &["init", "-q"][..],
            &["config", "user.email", "e2e@example.invalid"],
            &["config", "user.name", "e2e"],
            &["config", "commit.gpgsign", "false"],
            &["add", "-A"],
            &["commit", "-q", "-m", "fixture"],
        ] {
            let output = fixture.git(args);
            assert!(output.status.success(), "git {args:?} failed");
        }
        fixture
    }

    fn base(&self) -> PathBuf {
        self.repo.parent().unwrap().to_path_buf()
    }

    fn write(&self, relative: &str, text: &str) {
        let path = self.repo.join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }

    fn git(&self, args: &[&str]) -> Output {
        Command::new("git")
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.base())
            .args(args)
            .output()
            .unwrap()
    }

    fn legion(&self, args: &[&str]) -> Output {
        let registry =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/registry/providers.json");
        Command::new(env!("CARGO_BIN_EXE_legion"))
            .current_dir(&self.repo)
            .env("GIT_CEILING_DIRECTORIES", self.base())
            .env("HOME", &self.home)
            .env("USERPROFILE", &self.home)
            .env("LOCALAPPDATA", self.home.join("AppData/Local"))
            .env("XDG_DATA_HOME", self.home.join(".local/share"))
            .env("LEGION_STATE_ROOT", &self.state)
            .env("LEGION_PROVIDER_REGISTRY", registry)
            .env_remove("AUDIT_PLAN_SIGNING_KEY")
            .env_remove("LEGION_NATIVE_APPLICATION_CONFIG")
            .args(args)
            .output()
            .unwrap()
    }

    fn key_files(&self) -> Vec<PathBuf> {
        fs::read_dir(self.state.join("audit-plan-keys"))
            .map(|entries| entries.flatten().map(|entry| entry.path()).collect())
            .unwrap_or_default()
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(self.base());
    }
}

#[cfg(unix)]
fn restrict(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    fs::set_permissions(path, fs::Permissions::from_mode(0o600)).unwrap();
}

#[cfg(not(unix))]
fn restrict(_path: &Path) {}

fn json_of(label: &str, output: &Output) -> Value {
    serde_json::from_slice(&output.stdout).unwrap_or_else(|error| {
        panic!(
            "{label} stdout is not JSON ({error}): stdout={} stderr={}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        )
    })
}

fn tree_contains(dir: &Path, needle: &str) -> bool {
    fs::read_dir(dir).unwrap().flatten().any(|entry| {
        let path = entry.path();
        if path.is_dir() {
            tree_contains(&path, needle)
        } else {
            fs::read(&path)
                .map(|bytes| String::from_utf8_lossy(&bytes).contains(needle))
                .unwrap_or(false)
        }
    })
}

#[test]
fn new_run_has_no_epoch_key_and_keeps_its_plan_key_in_host_state() {
    let fixture = Fixture::new();
    let repo = fixture.repo.to_str().unwrap();
    let run = fixture.out.to_str().unwrap();
    let plan = fixture.legion(&["audit", repo, "--plan-only", "--out", run, "--json"]);
    assert!(
        matches!(plan.status.code(), Some(0) | Some(2)),
        "plan-only failed: {}",
        String::from_utf8_lossy(&plan.stderr)
    );
    assert!(
        !fixture.out.join("epoch.key").exists(),
        "new run wrote epoch.key into the run dir"
    );
    let stored: Value =
        serde_json::from_slice(&fs::read(fixture.out.join("plan.json")).unwrap()).unwrap();
    let binding = &stored["planKey"];
    assert_eq!(binding["custody"], "host-state");
    let run_id = binding["runId"].as_str().expect("run id recorded");
    let key_id = binding["keyId"].as_str().expect("key id recorded");
    let keys = fixture.key_files();
    assert_eq!(keys.len(), 1, "exactly one host key: {keys:?}");
    assert!(keys[0]
        .file_name()
        .unwrap()
        .to_string_lossy()
        .starts_with(run_id));
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        assert_eq!(
            fs::metadata(&keys[0]).unwrap().permissions().mode() & 0o777,
            0o600
        );
    }
    // The key material appears nowhere in the run tree; only its id does.
    let key_hex = fs::read_to_string(&keys[0]).unwrap();
    assert!(!tree_contains(&fixture.out, key_hex.trim()));
    assert!(key_id.starts_with("sha256:"));
    assert!(!fixture
        .out
        .starts_with(fixture.state.join("audit-plan-keys")));
}

#[test]
fn verify_uses_host_key_and_reports_unverifiable_when_it_is_missing_or_tampered() {
    let fixture = Fixture::new();
    let repo = fixture.repo.to_str().unwrap();
    let run = fixture.out.to_str().unwrap();
    let audit = fixture.legion(&["audit", repo, "--out", run, "--json"]);
    assert!(
        matches!(audit.status.code(), Some(0) | Some(2)),
        "audit failed: {}",
        String::from_utf8_lossy(&audit.stderr)
    );
    let keys = fixture.key_files();
    assert_eq!(keys.len(), 1, "host key stored: {keys:?}");

    // Host key present: verify succeeds on custody and is not a legacy warning.
    let verified = json_of("verify", &fixture.legion(&["verify", run, "--json"]));
    assert_eq!(verified["valid"], Value::Bool(true), "{verified:#}");
    assert_eq!(verified["keyCustody"], "host-state");
    assert!(verified["warnings"].as_array().unwrap().is_empty());

    // Tampered run dir: edit the sealed plan and plant a forged run-dir key.
    // The attacker cannot re-sign: the plan declares host custody, so the
    // planted epoch.key is never consulted and the changed digest finds no key.
    let plan_path = fixture.out.join("plan.json");
    let original = fs::read(&plan_path).unwrap();
    let mut plan: Value = serde_json::from_slice(&original).unwrap();
    plan["seal"]["digest"] = Value::String(format!("sha256:{}", "ab".repeat(32)));
    fs::write(&plan_path, serde_json::to_vec(&plan).unwrap()).unwrap();
    let epoch_path = fixture.out.join("epoch.key");
    let saved_epoch = fs::read(&epoch_path).ok();
    fs::write(&epoch_path, "11".repeat(32)).unwrap();
    restrict(&epoch_path);
    let tampered = json_of("tampered", &fixture.legion(&["verify", run, "--json"]));
    assert_ne!(tampered["valid"], Value::Bool(true), "{tampered:#}");
    assert_ne!(tampered["complete"], Value::Bool(true));
    fs::write(&plan_path, &original).unwrap();
    match saved_epoch {
        Some(bytes) => {
            fs::write(&epoch_path, bytes).unwrap();
            restrict(&epoch_path);
        }
        None => fs::remove_file(&epoch_path).unwrap(),
    }

    // Missing host key (and no env key): unverifiable-signature, not a pass.
    let hidden = keys[0].with_extension("hidden");
    fs::rename(&keys[0], &hidden).unwrap();
    let missing = json_of("missing", &fixture.legion(&["verify", run, "--json"]));
    assert_eq!(missing["status"], "unverifiable-signature", "{missing:#}");
    assert_ne!(missing["valid"], Value::Bool(true));
    assert_ne!(missing["complete"], Value::Bool(true));
    fs::rename(&hidden, &keys[0]).unwrap();
}

#[test]
fn legacy_run_dir_epoch_key_is_found_as_weak_custody() {
    use legion_audit::{PlanKeyResolution, PlanKeySource};
    if std::env::var_os("AUDIT_PLAN_SIGNING_KEY").is_some_and(|value| !value.is_empty()) {
        return; // an explicit environment key outranks every other source
    }
    let dir = std::env::temp_dir().join(format!("legion-legacy-key-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    let key = [7u8; 32];
    let path = dir.join("epoch.key");
    let hex: String = key.iter().map(|byte| format!("{byte:02x}")).collect();
    fs::write(&path, hex).unwrap();
    restrict(&path);
    // Legacy plan: no planKey binding recorded.
    let legacy = serde_json::json!({"seal": {"digest": format!("sha256:{}", "00".repeat(32))}});
    match legion_audit::resolve_plan_key(&dir, &legacy) {
        PlanKeyResolution::Found { key: found, source } => {
            assert_eq!(found, key);
            assert_eq!(source, PlanKeySource::LegacyRunDirEpoch);
        }
        other => panic!("legacy key not found: {other:?}"),
    }
    // A plan that declares host custody never falls back to the run-dir key.
    let hosted = serde_json::json!({
        "planKey": {"runId": "run-0", "keyId": "sha256:00"},
        "seal": {"digest": format!("sha256:{}", "00".repeat(32))}
    });
    assert!(matches!(
        legion_audit::resolve_plan_key(&dir, &hosted),
        PlanKeyResolution::Unverifiable { .. }
    ));
    // No key anywhere: unverifiable.
    let empty = dir.join("empty");
    fs::create_dir_all(&empty).unwrap();
    assert!(matches!(
        legion_audit::resolve_plan_key(&empty, &legacy),
        PlanKeyResolution::Unverifiable { .. }
    ));
    let _ = fs::remove_dir_all(&dir);
}
