#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const canonDir = join(root, 'docs', 'current', 'atoms');
const pendingPath = join(root, 'docs', 'pending', 'README.md');

const canons = Object.freeze([
  ['Legion', 'legion.md'],
  ['Sage', 'sage.md'],
  ['Alchemist', 'alchemist.md'],
  ['Oracle', 'oracle.md'],
  ['Arcane', 'arcane.md'],
  ['Guard', 'guard.md'],
  ['Covenant', 'covenant.md'],
  ['Skills', 'skills.md'],
]);

const expectedHeader = Object.freeze([
  'ID', 'Parent', 'Owner', 'Scope', 'Observable behavior', 'Implementation',
  'Verification', 'Qualification', 'Delivery', 'Action', 'Evidence',
]);

const enums = Object.freeze({
  Scope: new Set(['COMMITTED', 'PROPOSED', 'EXCLUDED']),
  Implementation: new Set(['DELIVERED', 'PARTIAL', 'MISSING', 'UNKNOWN']),
  Verification: new Set(['FULL_PASS', 'FOCUSED_PASS', 'PENDING', 'FAILED', 'UNKNOWN']),
  Qualification: new Set(['PASS', 'NOT_REQUIRED', 'PENDING', 'FAILED', 'UNKNOWN']),
  Delivery: new Set(['DEPLOYED', 'INSTALLED', 'RELEASED', 'COMMITTED', 'LOCAL', 'UNKNOWN']),
  Action: new Set(['RETAIN', 'REPAIR_WIRE', 'EVIDENCE', 'ADD', 'REMOVE', 'SUPERSEDE']),
});

function cells(line) {
  return line.trim().slice(1, -1).split('|').map((cell) => cell.trim());
}

function tableAfter(markdown, heading) {
  const start = markdown.indexOf(`${heading}\n`);
  if (start < 0) throw new Error(`missing heading ${heading}`);
  const lines = markdown.slice(start + heading.length).split(/\r?\n/);
  const rows = [];
  let started = false;
  for (const line of lines) {
    if (!started && line.trim().startsWith('|')) started = true;
    if (started && !line.trim().startsWith('|')) break;
    if (started) rows.push(cells(line));
  }
  if (rows.length < 2) throw new Error(`missing table after ${heading}`);
  return rows;
}

function isSeparator(row) {
  return row.every((cell) => /^:?-{3,}:?$/.test(cell));
}

function parseCanon(owner, file) {
  const markdown = readFileSync(join(canonDir, file), 'utf8');
  const groupTable = tableAfter(markdown, '## Group register');
  const capabilityTable = tableAfter(markdown, '## Capability ledger');
  const groupRows = groupTable.slice(1).filter((row) => !isSeparator(row));
  const groups = new Set(groupRows.map((row) => row[0]));
  const header = capabilityTable[0];
  if (header.join('|') !== expectedHeader.join('|')) {
    throw new Error(`${file}: capability schema mismatch: ${header.join(' | ')}`);
  }
  const rows = capabilityTable.slice(1).filter((row) => !isSeparator(row)).map((row, index) => {
    if (row.length !== expectedHeader.length) {
      throw new Error(`${file}:${index + 1}: expected ${expectedHeader.length} fields, got ${row.length}`);
    }
    return Object.fromEntries(expectedHeader.map((name, field) => [name, row[field]]));
  });

  for (const row of rows) {
    if (!/^[A-Z]{3}-\d{3}$/.test(row.ID)) throw new Error(`${file}: invalid atom ID ${row.ID}`);
    if (row.Owner !== owner) throw new Error(`${file}:${row.ID}: owner ${row.Owner} != ${owner}`);
    if (!groups.has(row.Parent)) throw new Error(`${file}:${row.ID}: unknown parent ${row.Parent}`);
    for (const [field, allowed] of Object.entries(enums)) {
      if (!allowed.has(row[field])) throw new Error(`${file}:${row.ID}: invalid ${field} ${row[field]}`);
    }
    if (!row.Evidence.includes('@')) throw new Error(`${file}:${row.ID}: evidence lacks exact revision marker`);
  }
  return { owner, file, rows };
}

function closed(row) {
  return row.Implementation === 'DELIVERED'
    && ['FULL_PASS', 'FOCUSED_PASS'].includes(row.Verification)
    && ['PASS', 'NOT_REQUIRED'].includes(row.Qualification)
    && ['DEPLOYED', 'INSTALLED', 'RELEASED', 'COMMITTED'].includes(row.Delivery)
    && row.Evidence.includes('@');
}

function pendingMarkdown(parsed) {
  const total = parsed.reduce((sum, canon) => sum + canon.rows.length, 0);
  const open = parsed.flatMap((canon) => canon.rows.filter((row) => !closed(row)).map((row) => ({ ...row, canon })));
  const lines = [
    '# Legion pending capability work',
    '',
    '<!-- GENERATED by scripts/check-atomic-canons.mjs --write. Do not hand-edit. -->',
    '',
    `Canonical atoms: **${total}**  `,
    `Closed: **${total - open.length}**  `,
    `Open: **${open.length}**`,
    '',
    'Atomic state lives only in `docs/current/atoms/*.md`. This generated file is the only file permitted in `docs/pending/`; historical trackers live under `docs/provenance/migrations/`.',
    '',
    '## Summary',
    '',
    '| Subsystem | Total | Closed | Open |',
    '|---|---:|---:|---:|',
  ];
  for (const canon of parsed) {
    const canonOpen = canon.rows.filter((row) => !closed(row)).length;
    lines.push(`| [${canon.owner}](../current/atoms/${canon.file}) | ${canon.rows.length} | ${canon.rows.length - canonOpen} | ${canonOpen} |`);
  }
  lines.push('', '## Open atoms', '');
  if (open.length === 0) lines.push('None.', '');
  for (const canon of parsed) {
    const rows = canon.rows.filter((row) => !closed(row));
    if (rows.length === 0) continue;
    lines.push(`### ${canon.owner}`, '', '| Atom | Required action | Current deficit |', '|---|---|---|');
    for (const row of rows) {
      const deficit = `implementation=${row.Implementation}; verification=${row.Verification}; qualification=${row.Qualification}; delivery=${row.Delivery}`;
      lines.push(`| [${row.ID}](../current/atoms/${canon.file}) | ${row.Action} | ${deficit} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

export function validateAtomicCanons({ write = false } = {}) {
  const pendingFiles = readdirSync(dirname(pendingPath)).sort();
  if (pendingFiles.join('|') !== 'README.md') {
    throw new Error(`docs/pending must contain only README.md; found ${pendingFiles.join(', ')}`);
  }
  const parsed = canons.map(([owner, file]) => parseCanon(owner, file));
  const ids = new Set();
  const behaviors = new Set();
  for (const canon of parsed) {
    for (const row of canon.rows) {
      if (ids.has(row.ID)) throw new Error(`duplicate atom ID ${row.ID}`);
      ids.add(row.ID);
      const behavior = row['Observable behavior'].toLowerCase();
      if (behaviors.has(behavior)) throw new Error(`duplicate observable behavior: ${row['Observable behavior']}`);
      behaviors.add(behavior);
    }
  }
  const expectedPending = pendingMarkdown(parsed);
  if (write) writeFileSync(pendingPath, expectedPending, 'utf8');
  else if (readFileSync(pendingPath, 'utf8') !== expectedPending) {
    throw new Error('docs/pending/README.md is stale; run node scripts/check-atomic-canons.mjs --write');
  }
  return {
    canons: parsed.length,
    atoms: ids.size,
    closed: parsed.flatMap((canon) => canon.rows).filter(closed).length,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const result = validateAtomicCanons({ write: process.argv.includes('--write') });
    console.log(`atomic canons PASS: ${result.canons} subsystems, ${result.atoms} atoms, ${result.closed} closed`);
  } catch (error) {
    console.error(`atomic canons FAIL: ${error.message}`);
    process.exitCode = 1;
  }
}
